package CoreJavaConcepts;

public class TestNumbers {
    public static void main(String[] args) {
        int a = 5;
        a+=3;
        System.out.println(a);

        int b=5;
        b=+3;
        System.out.println(b);

        int c=5;
        c++;
        System.out.println(c);

        int d=5;
        ++d;
        System.out.println(d);
    }
}
